def digest(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda:f.read(1<<20),b''):h.update(block)
    return h.hexdigest()


def file_record(name):
    path=ROOT/name
    if not path.is_file():
        if name in OPTIONAL_FETCHED_FILES:
            return {
                'status':'missing_public_input',
                'restore_command':'python fetch_public_inputs.py --download --extract',
            }
        raise FileNotFoundError(f'Required manifest input is missing: {name}')
    return {'sha256':digest(path),'bytes':path.stat().st_size}


