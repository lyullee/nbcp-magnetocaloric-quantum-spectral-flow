function payload = qmagen_cylinder_pilot(Lx,Ly,D,ST)
  % One-stagger public-QMagen M0 cylinder pilot using Gao et al. parameters.
  if nargin < 1, Lx=6; end
  if nargin < 2, Ly=3; end
  if nargin < 3, D=8; end
  if nargin < 4, ST=0; end
  script_dir=fileparts(mfilename('fullpath'));project_root=fileparts(script_dir);
  repo=fullfile(project_root,'sources','raw','QMagen_public','V0.0');
  old_dir=pwd();cleanup=onCleanup(@()cd(old_dir));cd(fullfile(repo,'RunScript'));
  addpath(fullfile(repo,'UtilityFunc'));addpath(genpath(fullfile(repo,'SpinModel')));
  addpath(fullfile(repo,'ManyBodySolver'));addpath(fullfile(repo,'ManyBodySolver','TensorFunction'));
  addpath(genpath(fullfile(repo,'ManyBodySolver','XTRG')));
  addpath(genpath(fullfile(repo,'svd_lapack_interface')));
  addpath(fullfile(script_dir,'qmagen_octave_compat'),'-begin');
  global EVOFLAG EVO_check PLOTFLAG SAVEFLAG;
  EVOFLAG=0;EVO_check=0;PLOTFLAG=0;SAVEFLAG=0;

  Jzz_K=1.48;Jxy_K=0.88;gz=4.89;field_T=1.50;L=Lx*Ly;
  Para=struct('ManyBodySolver','XTRG','IntrcMap_Name','IntrcMap_TLXXZ', ...
    'd',2,'L',L,'Geo',struct('Lx',Lx,'Ly',Ly,'BCX','OBC','BCY','PBC','L',L), ...
    'Model',struct('J1xy',Jxy_K/Jzz_K,'J1z',1.0,'J2xy',0.0,'J2z',0.0, ...
                   'ES',Jzz_K,'g',[4.89,4.89,gz]), ...
    'Field',struct('h',[0,0,gz*0.67171381563*field_T/Jzz_K], ...
                   'B',[0,0,field_T]),'ThDQ','Cm','Parallel',false, ...
    'RunParallel',false,'RunParallelNum',1,'RunParallelmaxNumCompThreads',1, ...
    'tau',0.00025,'It',15,'D_list',D*ones(1,15),'MCrit',D, ...
    'Ver','Memory','VariProd_step_max',50,'VariSum_step_max',50, ...
    'SETTN_init_step_max',50,'TStr',sprintf('qmagen_%dx%d_D%d',Lx,Ly,D), ...
    'TStr_log',sprintf('st%d',ST));
  tmp=fullfile(repo,'Tmp',['tmp_',Para.TStr]);if ~exist(tmp,'dir'),mkdir(tmp);end
  started=tic();[H,Id,Op]=InitHam(Para);x=XTRG_Main(Para,H,Id,Op,ST,0);
  temperature_K=Jzz_K./x.beta(:);entropy=x.LnZ(:)+x.beta(:).*x.En(:);
  rows=cell(numel(x.beta),1);
  for i=1:numel(x.beta)
    rows{i}=struct('temperature_K',temperature_K(i),'beta_dimensionless',x.beta(i), ...
      'logZ_per_spin',x.LnZ(i),'energy_scaled_per_spin',x.En(i), ...
      'entropy_kB_per_spin',entropy(i));
  end
  payload=struct('engine','public QMagen XTRG','source_model','Gao et al. 2022 M0', ...
    'geometry',sprintf('%dx%d OBCx/PBCy',Lx,Ly),'N',L,'field_T',field_T, ...
    'bond_dimension',D,'stagger_index',ST,'tau',Para.tau,'iterations',Para.It, ...
    'elapsed_seconds',toc(started),'cold_row',rows{end},'rows',{rows});
  if ST==0
    out=fullfile(project_root,'results',sprintf('qmagen_cylinder_%dx%d_D%d.json',Lx,Ly,D));
  else
    out=fullfile(project_root,'results',sprintf('qmagen_cylinder_%dx%d_D%d_st%d.json',Lx,Ly,D,ST));
  end
  fid=fopen(out,'w');fprintf(fid,'%s',jsonencode(payload));fclose(fid);
  fprintf('QMagen cylinder %dx%d N=%d D=%d st=%d: T=%.6fK S=%.8f elapsed=%.1fs\n', ...
    Lx,Ly,L,D,ST,rows{end}.temperature_K,rows{end}.entropy_kB_per_spin,payload.elapsed_seconds);
end
