"""Low-magnon projection for a general Cartesian spin Hamiltonian.

Unlike :mod:`truncated_magnon_operator`, this implementation keeps every
down-magnon sector from zero through ``cutoff``.  It therefore supports the
``xz``, ``zx``, ``yz`` and ``zy`` tensor elements generated by a full 3-D
dipolar Ewald sum.  Those elements change magnon parity and cannot be kept in
the older even/odd projected operator.

The basis bit convention is the one used by the existing near-saturation
code: bit 1 denotes a down-spin magnon.  It is the bitwise complement of the
full-space convention in ``SpinHamiltonianOperator``.
"""
from __future__ import annotations

from math import comb

import numpy as np
from numba import njit
from scipy.sparse.linalg import LinearOperator

from magnon_sector import _colex_rank, _fill_fixed_popcount_basis


@njit(cache=True)
def _general_projected_matvec(
    states, diagonal, pair_i, pair_j, flip_i, flip_j, lookup,
    offsets, binom, cutoff, x,
):
    y = diagonal.astype(np.complex128) * x
    for p in range(states.size):
        state = states[p]
        q_state = 0
        tmp = state
        while tmp:
            q_state += int(tmp & np.uint64(1))
            tmp >>= np.uint64(1)

        for action in range(pair_i.size):
            i = pair_i[action]
            j = pair_j[action]
            bi = int((state >> np.uint64(i)) & np.uint64(1))
            bj = int((state >> np.uint64(j)) & np.uint64(1))
            coefficient = lookup[action, bi + 2 * bj]
            if coefficient == 0:
                continue

            target_q = q_state
            target = state
            if flip_i[action]:
                target_q += 1 - 2 * bi
                target ^= np.uint64(1) << np.uint64(i)
            if flip_j[action]:
                target_q += 1 - 2 * bj
                target ^= np.uint64(1) << np.uint64(j)
            if target_q < 0 or target_q > cutoff:
                continue
            target_index = offsets[target_q] + _colex_rank(target, binom)
            y[target_index] += coefficient * x[p]
    return y


@njit(cache=True)
def _general_projected_diagonal(states, pair_i, pair_j, pair_zz, n, field_energy):
    out = np.empty(states.size, dtype=np.float64)
    for p in range(states.size):
        state = states[p]
        q = 0
        tmp = state
        while tmp:
            q += int(tmp & np.uint64(1))
            tmp >>= np.uint64(1)
        value = -field_energy * (0.5 * n - q)
        for b in range(pair_i.size):
            bi = int((state >> np.uint64(pair_i[b])) & np.uint64(1))
            bj = int((state >> np.uint64(pair_j[b])) & np.uint64(1))
            value += pair_zz[b] * (0.5 - bi) * (0.5 - bj)
        out[p] = value
    return out


def _transverse_coefficient(axis: int, down_bit: int) -> complex:
    if axis == 0:
        return 0.5
    if axis == 1:
        # Full-space bit is 1-down_bit, so Sy=.5j*(2*bit_full-1).
        return 0.5j * (1 - 2 * down_bit)
    if axis == 2:
        return 0.5 - down_bit
    raise ValueError(axis)


class GeneralTruncatedMagnonCartesianOperator(LinearOperator):
    """Cartesian Hamiltonian projected to all q=0,...,cutoff sectors."""

    def __init__(self, n: int, cutoff: int, bonds, field_energy_k: float):
        self.n = int(n)
        self.cutoff = min(int(cutoff), self.n)
        if self.n > 63:
            raise ValueError("uint64 basis supports at most 63 spins")
        if self.cutoff < 0:
            raise ValueError("cutoff must be non-negative")

        combined = {}
        for bond in bonds:
            i, j = int(bond.i), int(bond.j)
            tensor = np.asarray(bond.coupling_K, dtype=np.complex128)
            if tensor.shape != (3, 3):
                raise ValueError("bond tensor must be 3x3")
            if i > j:
                i, j = j, i
                tensor = tensor.T
            combined[(i, j)] = combined.get((i, j), np.zeros((3, 3), complex)) + tensor
        items = sorted(combined.items())

        pair_i = np.asarray([key[0] for key, _ in items], dtype=np.int16)
        pair_j = np.asarray([key[1] for key, _ in items], dtype=np.int16)
        pair_zz = np.asarray([tensor[2, 2].real for _, tensor in items], dtype=np.float64)

        action_i = []
        action_j = []
        action_flip_i = []
        action_flip_j = []
        action_lookup = []
        for (i, j), tensor in items:
            grouped = {}
            for a in range(3):
                for c in range(3):
                    value = tensor[a, c]
                    if (a, c) == (2, 2) or abs(value) < 1e-15:
                        continue
                    grouped.setdefault((a < 2, c < 2), []).append((a, c, value))
            for (fi, fj), components in grouped.items():
                local_lookup = np.empty(4, dtype=np.complex128)
                for local in range(4):
                    bi = local & 1
                    bj = (local >> 1) & 1
                    local_lookup[local] = sum(
                        value * _transverse_coefficient(a, bi)
                        * _transverse_coefficient(c, bj)
                        for a, c, value in components
                    )
                action_i.append(i)
                action_j.append(j)
                action_flip_i.append(fi)
                action_flip_j.append(fj)
                action_lookup.append(local_lookup)

        self.pair_i = pair_i
        self.pair_j = pair_j
        self.pair_zz = pair_zz
        self.action_i = np.asarray(action_i, dtype=np.int16)
        self.action_j = np.asarray(action_j, dtype=np.int16)
        self.action_flip_i = np.asarray(action_flip_i, dtype=np.bool_)
        self.action_flip_j = np.asarray(action_flip_j, dtype=np.bool_)
        self.action_lookup = np.asarray(action_lookup, dtype=np.complex128)

        blocks = []
        self.offsets = np.zeros(self.cutoff + 1, dtype=np.int64)
        offset = 0
        for q in range(self.cutoff + 1):
            self.offsets[q] = offset
            block = _fill_fixed_popcount_basis(self.n, q, comb(self.n, q))
            blocks.append(block)
            offset += block.size
        self.states = np.concatenate(blocks)

        self.binom = np.zeros((self.n + 1, self.cutoff + 2), dtype=np.int64)
        for p in range(self.n + 1):
            for rank in range(min(p, self.cutoff + 1) + 1):
                self.binom[p, rank] = comb(p, rank)
        self.diagonal = _general_projected_diagonal(
            self.states, self.pair_i, self.pair_j, self.pair_zz,
            self.n, float(field_energy_k),
        )
        super().__init__(dtype=np.dtype(np.complex128), shape=(self.states.size, self.states.size))

    def _matvec(self, x):
        return _general_projected_matvec(
            self.states, self.diagonal,
            self.action_i, self.action_j,
            self.action_flip_i, self.action_flip_j, self.action_lookup,
            self.offsets, self.binom, self.cutoff,
            np.asarray(x, dtype=np.complex128),
        )

    def _rmatvec(self, x):
        return self._matvec(x)
